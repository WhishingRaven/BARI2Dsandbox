from __future__ import annotations

from dataclasses import dataclass
from math import inf
from typing import Iterable, Mapping, Sequence

import numpy as np

from bari2d.env.contact_model import ContactGraph, MechanicalEdge, Node
from bari2d.env.field import LEFT_BANK, RIGHT_BANK, GapField
from bari2d.env.robot import RobotState
from bari2d.utils.config import RobotConfig


EdgeKey = frozenset[Node]


@dataclass(frozen=True)
class PlanarWrench:
    """Planar wrench expressed in world axes.

    fx, fy are forces [N] and mz is the pure couple at the contact point [N m].
    The moment generated by the contact force about a robot COM is not included
    in mz; it is r x F and is assembled separately by the rigid-body model.
    """

    fx: float
    fy: float
    mz: float

    def as_array(self) -> np.ndarray:
        return np.asarray([self.fx, self.fy, self.mz], dtype=float)

    @classmethod
    def from_array(cls, values: np.ndarray) -> "PlanarWrench":
        values = np.asarray(values, dtype=float)
        return cls(float(values[0]), float(values[1]), float(values[2]))


@dataclass(frozen=True)
class PlanarWrenchLimit:
    """Component-wise absolute contact limits in world axes."""

    fx: float = inf
    fy: float = inf
    mz: float = inf

    def as_array(self) -> np.ndarray:
        return np.asarray([self.fx, self.fy, self.mz], dtype=float)


@dataclass(frozen=True)
class PlanarLoad:
    """External planar load applied to one robot.

    `point` is a world-coordinate application point. If omitted, the force is
    applied at the robot COM. `moment` is an additional free couple [N m].
    """

    robot_id: int
    force: tuple[float, float]
    point: tuple[float, float] | None = None
    moment: float = 0.0


@dataclass(frozen=True)
class ContactResponse:
    source: Node
    target: Node
    kind: str
    point: tuple[float, float]
    wrench_on_source: PlanarWrench
    relative_displacement: tuple[float, float, float]

    @property
    def key(self) -> EdgeKey:
        return frozenset((self.source, self.target))


@dataclass
class PlanarStaticResult:
    stable: bool
    displacements: dict[int, tuple[float, float, float]]
    contacts: list[ContactResponse]
    residual_norm: float
    rank: int
    dof_count: int
    failure_mode: str = "none"

    def contact_by_key(self) -> dict[EdgeKey, ContactResponse]:
        return {contact.key: contact for contact in self.contacts}


@dataclass
class PlanarCapacityResult:
    max_payload_kg: float
    failure_mode: str
    critical_contact: tuple[Node, Node] | None
    critical_component: str | None
    critical_limit: float | None
    critical_value: float | None
    base_response: PlanarStaticResult
    unit_payload_response: PlanarStaticResult


@dataclass(frozen=True)
class _ContactElement:
    edge: MechanicalEdge
    point: np.ndarray
    B: np.ndarray
    stiffness: np.ndarray


_COMPONENT_NAMES = ("Fx", "Fy", "Mz")


def _cross2(r: np.ndarray, force: np.ndarray) -> float:
    return float(r[0] * force[1] - r[1] * force[0])


def _rotation(theta: float) -> np.ndarray:
    c, s = np.cos(theta), np.sin(theta)
    return np.asarray([[c, -s], [s, c]], dtype=float)


def robot_face_centers(robot: RobotState, config: RobotConfig) -> np.ndarray:
    """World-coordinate centers of the four rectangular robot faces."""
    local = np.asarray(
        [
            [config.length / 2.0, 0.0],
            [-config.length / 2.0, 0.0],
            [0.0, config.width / 2.0],
            [0.0, -config.width / 2.0],
        ],
        dtype=float,
    )
    return local @ _rotation(robot.theta).T + robot.position


def _face_toward(robot: RobotState, direction: np.ndarray, config: RobotConfig) -> np.ndarray:
    direction = np.asarray(direction, dtype=float)
    norm = float(np.linalg.norm(direction))
    if norm <= 1.0e-12:
        return np.asarray(robot.position, dtype=float).copy()
    direction = direction / norm
    centers = robot_face_centers(robot, config)
    scores = (centers - robot.position) @ direction
    return centers[int(np.argmax(scores))]


def contact_point_for_edge(
    edge: MechanicalEdge,
    robots: Sequence[RobotState],
    field: GapField,
    robot_config: RobotConfig,
) -> np.ndarray:
    """Estimate the physical center at which an edge transmits its wrench.

    Robot-robot edges use the midpoint of the two opposing face centers. Bank
    edges use the center of the robot face directed into that bank. This is a
    deterministic geometric construction and intentionally does not use the old
    scalar `edge.force` proxy.
    """
    if isinstance(edge.source, int) and isinstance(edge.target, int):
        first = robots[edge.source]
        second = robots[edge.target]
        direction = np.asarray(second.position - first.position, dtype=float)
        if float(np.linalg.norm(direction)) <= 1.0e-12:
            # Degenerate stacked projection: use the source heading so the
            # result remains deterministic in the 2-D approximation.
            direction = first.heading
        first_face = _face_toward(first, direction, robot_config)
        second_face = _face_toward(second, -direction, robot_config)
        return 0.5 * (first_face + second_face)

    robot_id = edge.source if isinstance(edge.source, int) else edge.target
    bank = edge.target if isinstance(edge.source, int) else edge.source
    if not isinstance(robot_id, int):
        raise ValueError(f"Mechanical edge has no robot endpoint: {edge}")
    robot = robots[robot_id]
    if bank == LEFT_BANK:
        direction = -field.normal
    elif bank == RIGHT_BANK:
        direction = field.normal
    else:
        raise ValueError(f"Unsupported fixed endpoint: {bank!r}")
    return _face_toward(robot, direction, robot_config)


class PlanarStaticSolver:
    """Linear-elastic rigid-body statics for the current BARI2D geometry.

    Each robot has three small-displacement DOFs: (ux, uy, theta). Every graph
    edge is represented as a 3-DOF spring located at the contact/anchor face
    center. Bank nodes are fixed supports. This resolves load sharing in
    statically indeterminate bridge graphs while preserving exact force and
    moment equilibrium for the assumed linear spring model.

    The present environment is top-view/2.5-D. Therefore this solver is a
    verification model for in-plane (Fx, Fy, Mz) mechanics, not gravity sagging.
    The same assembly extends directly to 6-DOF contacts in the future 3-D model.
    """

    def __init__(
        self,
        robots: Sequence[RobotState],
        graph: ContactGraph,
        field: GapField,
        robot_config: RobotConfig,
        *,
        rotational_stiffness_scale: float = 1.0 / 12.0,
        rank_tolerance: float = 1.0e-10,
    ):
        self.robots = list(robots)
        self.graph = graph
        self.field = field
        self.robot_config = robot_config
        self.rotational_stiffness_scale = float(rotational_stiffness_scale)
        self.rank_tolerance = float(rank_tolerance)

    def _component_for_loads(self, loads: Sequence[PlanarLoad]) -> set[int]:
        requested = {load.robot_id for load in loads}
        for robot_id in requested:
            if robot_id < 0 or robot_id >= len(self.robots):
                raise IndexError(f"Invalid robot_id {robot_id}")
            if self.robots[robot_id].fallen:
                raise ValueError(f"Cannot apply a static load to fallen robot {robot_id}")

        active: set[int] = set()
        for start in requested:
            component = self.graph.connected_component(start)
            active.update(node for node in component if isinstance(node, int))
        return active

    def _element(
        self,
        edge: MechanicalEdge,
        index: Mapping[int, int],
        dof_count: int,
    ) -> _ContactElement | None:
        robot_endpoints = [node for node in (edge.source, edge.target) if isinstance(node, int)]
        if not any(node in index for node in robot_endpoints):
            return None

        point = contact_point_for_edge(edge, self.robots, self.field, self.robot_config)
        B = np.zeros((3, dof_count), dtype=float)

        def add_endpoint(node: Node, sign: float) -> None:
            if not isinstance(node, int) or node not in index:
                return
            base = 3 * index[node]
            r = point - self.robots[node].position
            jr = np.asarray([-r[1], r[0]], dtype=float)
            B[0:2, base : base + 2] += sign * np.eye(2)
            B[0:2, base + 2] += sign * jr
            B[2, base + 2] += sign

        # Relative contact deformation = target - source.
        add_endpoint(edge.source, -1.0)
        add_endpoint(edge.target, +1.0)

        k_translation = max(float(edge.stiffness), 1.0e-9)
        characteristic_length = max(float(self.robot_config.length), float(self.robot_config.width), 1.0e-9)
        k_rotation = max(
            k_translation * characteristic_length**2 * self.rotational_stiffness_scale,
            1.0e-9,
        )
        stiffness = np.diag([k_translation, k_translation, k_rotation])
        return _ContactElement(edge=edge, point=point, B=B, stiffness=stiffness)

    def solve(self, loads: Iterable[PlanarLoad]) -> PlanarStaticResult:
        loads = tuple(loads)
        if not loads:
            return PlanarStaticResult(True, {}, [], 0.0, 0, 0)

        active = self._component_for_loads(loads)
        if not active:
            return PlanarStaticResult(False, {}, [], inf, 0, 0, "unsupported_component")

        component_nodes: set[Node] = set(active)
        for node in tuple(active):
            component_nodes.update(self.graph.connected_component(node))
        has_fixed_support = LEFT_BANK in component_nodes or RIGHT_BANK in component_nodes
        if not has_fixed_support:
            return PlanarStaticResult(False, {}, [], inf, 0, 3 * len(active), "unsupported_component")

        ordered = sorted(active)
        index = {robot_id: i for i, robot_id in enumerate(ordered)}
        dof_count = 3 * len(ordered)
        K = np.zeros((dof_count, dof_count), dtype=float)
        force = np.zeros(dof_count, dtype=float)
        elements: list[_ContactElement] = []

        for edge in self.graph.edges.values():
            element = self._element(edge, index, dof_count)
            if element is None:
                continue
            # Keep only edges entirely inside this robot component, or edges to
            # a fixed bank. Cross-component robot edges cannot occur by graph
            # definition but this guard makes the assembly explicit.
            robot_nodes = [node for node in (edge.source, edge.target) if isinstance(node, int)]
            if any(node not in active for node in robot_nodes):
                continue
            K += element.B.T @ element.stiffness @ element.B
            elements.append(element)

        for load in loads:
            if load.robot_id not in index:
                continue
            base = 3 * index[load.robot_id]
            applied_force = np.asarray(load.force, dtype=float)
            point = (
                np.asarray(load.point, dtype=float)
                if load.point is not None
                else np.asarray(self.robots[load.robot_id].position, dtype=float)
            )
            r = point - self.robots[load.robot_id].position
            force[base : base + 2] += applied_force
            force[base + 2] += _cross2(r, applied_force) + float(load.moment)

        if dof_count == 0:
            return PlanarStaticResult(False, {}, [], inf, 0, 0, "unsupported_component")

        singular_values = np.linalg.svd(K, compute_uv=False)
        largest = float(singular_values[0]) if singular_values.size else 0.0
        threshold = self.rank_tolerance * max(largest, 1.0)
        rank = int(np.count_nonzero(singular_values > threshold))

        # Least squares is deliberate: it lets us measure whether an external
        # load lies outside the supported stiffness subspace instead of hiding a
        # mechanism with artificial numerical regularization.
        q, _, _, _ = np.linalg.lstsq(K, force, rcond=self.rank_tolerance)
        residual = K @ q - force
        residual_norm = float(np.linalg.norm(residual))
        force_scale = max(float(np.linalg.norm(force)), 1.0)
        stable = rank == dof_count and residual_norm <= 1.0e-8 * force_scale
        failure_mode = "none" if stable else "mechanism"

        displacements = {
            robot_id: (
                float(q[3 * i]),
                float(q[3 * i + 1]),
                float(q[3 * i + 2]),
            )
            for i, robot_id in enumerate(ordered)
        }

        contacts: list[ContactResponse] = []
        for element in elements:
            relative = element.B @ q
            wrench = element.stiffness @ relative
            contacts.append(
                ContactResponse(
                    source=element.edge.source,
                    target=element.edge.target,
                    kind=element.edge.kind,
                    point=(float(element.point[0]), float(element.point[1])),
                    wrench_on_source=PlanarWrench.from_array(wrench),
                    relative_displacement=(float(relative[0]), float(relative[1]), float(relative[2])),
                )
            )

        return PlanarStaticResult(
            stable=stable,
            displacements=displacements,
            contacts=contacts,
            residual_norm=residual_norm,
            rank=rank,
            dof_count=dof_count,
            failure_mode=failure_mode,
        )

    def capacity(
        self,
        payload_per_kg: PlanarLoad,
        limits: PlanarWrenchLimit | Mapping[EdgeKey, PlanarWrenchLimit],
        *,
        base_loads: Iterable[PlanarLoad] = (),
    ) -> PlanarCapacityResult:
        """Return the first component-wise contact limit reached by payload mass.

        Owing to linear statics, contact wrench is affine in payload mass:

            w(m) = w_base + m * w_1kg

        Therefore no incremental mass sweep is necessary.
        """
        base_loads = tuple(base_loads)
        # Solve the same connected component for both responses. A zero external
        # base load would otherwise have no component to assemble, so add a zero
        # load at the payload robot as a topology selector.
        selector = PlanarLoad(payload_per_kg.robot_id, (0.0, 0.0), payload_per_kg.point, 0.0)
        base_response = self.solve((*base_loads, selector))
        unit_response = self.solve((payload_per_kg,))

        if not base_response.stable or not unit_response.stable:
            return PlanarCapacityResult(
                0.0,
                "mechanism",
                None,
                None,
                None,
                None,
                base_response,
                unit_response,
            )

        base_by_key = base_response.contact_by_key()
        unit_by_key = unit_response.contact_by_key()

        def limit_for(key: EdgeKey) -> PlanarWrenchLimit:
            if isinstance(limits, PlanarWrenchLimit):
                return limits
            return limits.get(key, PlanarWrenchLimit())

        best_mass = inf
        best_contact: ContactResponse | None = None
        best_component: str | None = None
        best_limit: float | None = None
        best_value: float | None = None

        all_keys = set(base_by_key) | set(unit_by_key)
        for key in all_keys:
            base_contact = base_by_key.get(key)
            unit_contact = unit_by_key.get(key)
            representative = base_contact or unit_contact
            if representative is None:
                continue
            a = base_contact.wrench_on_source.as_array() if base_contact is not None else np.zeros(3)
            b = unit_contact.wrench_on_source.as_array() if unit_contact is not None else np.zeros(3)
            max_values = limit_for(key).as_array()

            for component_index, (a_value, b_value, maximum) in enumerate(zip(a, b, max_values)):
                if maximum < 0.0:
                    raise ValueError("Wrench limits must be non-negative")
                if not np.isfinite(maximum):
                    continue
                if abs(a_value) > maximum + 1.0e-12:
                    candidate = 0.0
                elif abs(b_value) <= 1.0e-12:
                    candidate = inf
                elif b_value > 0.0:
                    candidate = (maximum - a_value) / b_value
                else:
                    candidate = (-maximum - a_value) / b_value
                candidate = max(float(candidate), 0.0)
                if candidate < best_mass:
                    best_mass = candidate
                    best_contact = representative
                    best_component = _COMPONENT_NAMES[component_index]
                    best_limit = float(maximum)
                    best_value = float(a_value + candidate * b_value)

        if best_contact is None:
            return PlanarCapacityResult(
                inf,
                "none",
                None,
                None,
                None,
                None,
                base_response,
                unit_response,
            )

        return PlanarCapacityResult(
            max_payload_kg=float(best_mass),
            failure_mode="contact_limit",
            critical_contact=(best_contact.source, best_contact.target),
            critical_component=best_component,
            critical_limit=best_limit,
            critical_value=best_value,
            base_response=base_response,
            unit_payload_response=unit_response,
        )


def bridge_center_payload(
    robots: Sequence[RobotState],
    graph: ContactGraph,
    field: GapField,
    *,
    gravity: float = 9.81,
    direction: tuple[float, float] = (0.0, -1.0),
) -> PlanarLoad:
    """Choose the spanning robot nearest the geometric gap center for a 1 kg load.

    `direction` is an in-plane direction because BARI2D has no vertical DOF.
    It exists only for planar mechanics verification; a future 3-D model should
    use the physical gravity vector instead.
    """
    component = graph.connected_component(LEFT_BANK)
    candidates = [node for node in component if isinstance(node, int) and RIGHT_BANK in graph.connected_component(node)]
    if not candidates:
        raise ValueError("Bridge does not span both banks")

    direction_array = np.asarray(direction, dtype=float)
    norm = float(np.linalg.norm(direction_array))
    if norm <= 1.0e-12:
        raise ValueError("Payload direction must be non-zero")
    direction_array /= norm

    target = field.center
    robot_id = min(candidates, key=lambda node: float(np.linalg.norm(robots[node].position - target)))
    force = gravity * direction_array
    return PlanarLoad(
        robot_id=robot_id,
        force=(float(force[0]), float(force[1])),
        point=(float(robots[robot_id].position[0]), float(robots[robot_id].position[1])),
    )
